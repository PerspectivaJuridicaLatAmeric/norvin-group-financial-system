import React from "react";

const TYPES = [
  ["estimate","Estimate"],
  ["invoice","Invoice"],
  ["purchase-order","Purchase Order"],
  ["payroll-statement","Payroll Statement"],
  ["expense-report","Expense Report"]
];

export default function DocumentsModule(){
  const [type,setType]=React.useState("estimate");
  const [number,setNumber]=React.useState("");
  const [name,setName]=React.useState("");
  const [amount,setAmount]=React.useState("");
  const [date,setDate]=React.useState(new Date().toISOString().slice(0,10));
  const label=TYPES.find(([key])=>key===type)?.[1] || "Document";
  return <section className="document-module">
    <div className="toolbar"><div><strong>Documents</strong><div className="muted">PRINTABLE BUSINESS DOCUMENTS</div></div></div>
    <div className="formgrid no-print">
      <label>Document type<select value={type} onChange={e=>setType(e.target.value)}>{TYPES.map(([k,v])=><option key={k} value={k}>{v}</option>)}</select></label>
      <label>Document number<input value={number} onChange={e=>setNumber(e.target.value)}/></label>
      <label>Client / Payee<input value={name} onChange={e=>setName(e.target.value)}/></label>
      <label>Amount<input type="number" step="0.01" value={amount} onChange={e=>setAmount(e.target.value)}/></label>
      <label>Date<input type="date" value={date} onChange={e=>setDate(e.target.value)}/></label>
      <div className="formactions"><button className="primary" type="button" onClick={()=>window.print()}>Print / Save PDF</button></div>
    </div>
    <article className="print-sheet">
      <header><h1>NORVIN GROUP LLC</h1><h2>{label}</h2></header>
      <div><strong>Document #:</strong> {number||"—"}</div>
      <div><strong>Date:</strong> {date}</div>
      <div><strong>Client / Payee:</strong> {name||"—"}</div>
      <div><strong>Amount:</strong> {amount ? new Intl.NumberFormat("en-US",{style:"currency",currency:"USD"}).format(Number(amount)) : "$0.00"}</div>
      <footer>Generated by NORVIN GROUP LLC Financial System</footer>
    </article>
  </section>;
}
